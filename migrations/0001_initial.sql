CREATE TABLE admin (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    login TEXT NOT NULL,
    password TEXT NOT NULL
);
CREATE TABLE sessions (
    token TEXT PRIMARY KEY,
    expires TIMESTAMPTZ NOT NULL
);
CREATE TABLE levels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    color TEXT NOT NULL CHECK (color ~ '^#[0-9a-fA-F]{6}$'),
    position BIGINT NOT NULL,
    archived BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL DEFAULT 'Новая инструкция',
    steps JSONB NOT NULL DEFAULT '[]',
    revision BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id BIGINT NOT NULL REFERENCES drafts(id),
    snapshot JSONB NOT NULL
);
CREATE INDEX releases_draft ON releases (draft_id, id);
CREATE TABLE links (
    token TEXT PRIMARY KEY,
    release_id BIGINT NOT NULL REFERENCES releases(id),
    level_id BIGINT NOT NULL REFERENCES levels(id),
    UNIQUE (release_id, level_id)
);
CREATE TABLE images (
    id TEXT PRIMARY KEY,
    content BYTEA NOT NULL
);
